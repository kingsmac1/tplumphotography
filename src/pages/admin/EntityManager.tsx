/* eslint-disable @typescript-eslint/no-explicit-any */
import { useEffect, useMemo, useRef, useState, type ReactNode } from "react";
import { ArrowDown, ArrowUp, Loader2, Pencil, Plus, Search, Trash2, Upload, X } from "lucide-react";
import { supabase } from "@/lib/supabaseClient";
import { markManaged, resetContentCache } from "@/lib/content";
import { deleteImagePaths, uploadImage } from "@/lib/githubMedia";
import { Table, TableBody, TableCell, TableHead, TableHeader, TableRow } from "@/components/ui/table";
import { Checkbox } from "@/components/ui/checkbox";
import ConfirmDialog from "./ConfirmDialog";
import {
  BulkActionBar, BulkButton, stickyCheckCell, stickyCheckHead, stickySnCell, stickySnHead, useRowSelection,
} from "./bulk";

type Row = Record<string, any>;

export type Field = {
  key: string;
  label: string;
  type: "text" | "textarea" | "lines" | "number" | "date" | "image" | "bool" | "select";
  help?: string;
  rows?: number;
  required?: boolean;
  nullable?: boolean;            // number: empty saves as null
  options?: { value: string; label: string }[]; // select
  pathKey?: string;              // image: column that stores the GitHub file path
  lockOnEdit?: boolean;          // can't be changed once created
  half?: boolean;                // show two per row
};

export type ListColumn = {
  label: string;
  render?: (row: Row) => ReactNode;
  inline?: { key: string };      // editable number, saved when you leave the box
  switch?: { key: string };      // clickable on/off switch, saved immediately on click
};

export type EntityConfig = {
  title: string;
  noun: string;
  table: string;
  idKey: string;
  uuid?: boolean;                // ids are generated by the database
  flagKey?: string;              // content_flags key (managed by this table alone)
  fields: Field[];
  columns: ListColumn[];
  orderBy: { column: string; ascending?: boolean };
  reorderKey?: string;           // column holding the display order
  toggle?: { key: string; on: string; off: string };
  bulkActions?: { label: string; patch: Row }[];  // extra one-click actions for ticked rows
  fixedOnCreate?: Row;           // values always set on new rows (not shown in the form)
  filters?: { key: string; label: string; options: { value: string; label: string }[] }[];
  slugFrom?: string;             // field the id is built from (text ids)
  newDefaults: Row;
  imageFolder?: string;
  importDefaults?: () => Promise<Row[]>;
  beforeSave?: (payload: Row) => void;
  intro?: string;
  gated?: boolean;               // parent handles the "load current data" step
};

const inputCls = "w-full border border-border bg-background px-3 py-2 text-sm font-body outline-none focus:border-foreground";
const primaryBtn = "inline-flex items-center gap-2 px-4 py-2 text-sm font-body font-medium bg-primary text-primary-foreground rounded-md hover:bg-primary/90 disabled:opacity-50";
const ghostBtn = "inline-flex items-center gap-2 px-4 py-2 text-sm font-body font-medium border border-border rounded-md hover:bg-muted/50 disabled:opacity-50";

const slugify = (s: string) => s.toLowerCase().trim().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

/* ---------------- single image picker ---------------- */
const ImagePicker = ({ url, onPicked, folder }: { url: string; onPicked: (v: { url: string; path: string }) => void; folder: string }) => {
  const ref = useRef<HTMLInputElement>(null);
  const [busy, setBusy] = useState(false);
  const [err, setErr] = useState("");
  const pick = async (file?: File) => {
    if (!file) return;
    setBusy(true); setErr("");
    try { onPicked(await uploadImage(file, folder)); }
    catch (e) { setErr(e instanceof Error ? e.message : "Upload failed"); }
    finally { setBusy(false); if (ref.current) ref.current.value = ""; }
  };
  return (
    <div className="flex items-center gap-4">
      <div className="w-32 h-24 bg-muted grid place-items-center overflow-hidden border border-border">
        {url ? <img src={url} alt="" className="w-full h-full object-cover" /> : <span className="text-[10px] text-muted-foreground">NO IMAGE</span>}
      </div>
      <div className="space-y-2">
        <input ref={ref} type="file" accept="image/*" className="hidden" onChange={(e) => void pick(e.target.files?.[0])} />
        <button type="button" className={ghostBtn} disabled={busy} onClick={() => ref.current?.click()}>
          {busy ? <Loader2 size={16} className="animate-spin" /> : <Upload size={16} />} {url ? "Replace image" : "Upload image"}
        </button>
        {err && <p className="text-xs text-destructive">{err}</p>}
      </div>
    </div>
  );
};

/* ---------------- the manager ---------------- */
const EntityManager = ({ cfg }: { cfg: EntityConfig }) => {
  const [rows, setRows] = useState<Row[]>([]);
  const [loading, setLoading] = useState(true);
  const [managed, setManaged] = useState<boolean | null>(cfg.gated || !cfg.flagKey ? true : null);
  const [error, setError] = useState("");
  const [msg, setMsg] = useState("");
  const [search, setSearch] = useState("");
  const [filterVals, setFilterVals] = useState<Record<string, string>>({});
  const [editing, setEditing] = useState<Row | "new" | null>(null);
  const [values, setValues] = useState<Row>({});
  const [saving, setSaving] = useState(false);
  const [formError, setFormError] = useState("");
  const [oldPath, setOldPath] = useState<string | null>(null);
  const [confirmIds, setConfirmIds] = useState<string[] | null>(null);
  const [importing, setImporting] = useState(false);
  const sel = useRowSelection();

  const load = async () => {
    const { data, error: err } = await supabase
      .from(cfg.table)
      .select("*")
      .order(cfg.orderBy.column, { ascending: cfg.orderBy.ascending ?? true });
    if (err) setError(err.message);
    else { setRows(data || []); setError(""); }
    setLoading(false);
  };

  useEffect(() => {
    void load();
    if (cfg.flagKey && !cfg.gated) {
      supabase.from("content_flags").select("managed").eq("key", cfg.flagKey).maybeSingle().then(({ data }) => setManaged(!!data?.managed));
    }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [cfg.table]);

  const visible = useMemo(() => {
    const q = search.trim().toLowerCase();
    return rows.filter((r) => {
      if (q && !JSON.stringify(Object.values(r)).toLowerCase().includes(q)) return false;
      return (cfg.filters ?? []).every((f) => !filterVals[f.key] || String(r[f.key]) === filterVals[f.key]);
    });
  }, [rows, search, filterVals, cfg.filters]);

  const visibleIds = visible.map((r) => String(r[cfg.idKey]));
  const selectedIds = visibleIds.filter((id) => sel.ids.has(id));

  const afterChange = async () => {
    resetContentCache();
    await load();
  };

  const loadCurrent = async () => {
    if (!cfg.importDefaults || !cfg.flagKey) return;
    setImporting(true); setError("");
    try {
      const data = await cfg.importDefaults();
      const { error: err } = await supabase.from(cfg.table).insert(data);
      if (err) throw new Error(err.message);
      await markManaged(cfg.flagKey);
      setManaged(true);
      await load();
    } catch (e) {
      setError(e instanceof Error ? e.message : "Import failed");
    } finally { setImporting(false); }
  };

  const startEmpty = async () => {
    if (!cfg.flagKey) return;
    await markManaged(cfg.flagKey);
    setManaged(true);
  };

  const openNew = () => {
    setEditing("new");
    setValues({ ...cfg.newDefaults });
    setOldPath(null); setFormError("");
  };
  const openEdit = (r: Row) => {
    setEditing(r);
    const v: Row = { ...r };
    cfg.fields.forEach((f) => { if (f.type === "lines") v[f.key] = (r[f.key] ?? []).join("\n"); });
    setValues(v);
    setOldPath(null); setFormError("");
  };

  const save = async () => {
    for (const f of cfg.fields) {
      if (f.required && (values[f.key] === undefined || values[f.key] === null || String(values[f.key]).trim() === "")) {
        return setFormError(`${f.label} is required.`);
      }
    }
    setSaving(true); setFormError("");
    const payload: Row = {};
    cfg.fields.forEach((f) => {
      let v = values[f.key];
      if (f.type === "number") v = v === "" || v === null || v === undefined ? (f.nullable ? null : 0) : Number(v);
      if (f.type === "lines") v = String(v ?? "").split("\n").map((l) => l.trim()).filter(Boolean);
      if (f.type === "date" && !v) v = null;
      payload[f.key] = v;
      if (f.type === "image" && f.pathKey) payload[f.pathKey] = values[f.pathKey] ?? null;
    });
    cfg.beforeSave?.(payload);
    try {
      if (editing === "new") {
        if (!cfg.uuid) {
          const base = slugify(String(values[cfg.slugFrom ?? cfg.fields[0].key] ?? "")) || "item";
          let id = base, n = 2;
          while (rows.some((r) => r[cfg.idKey] === id)) id = `${base}-${n++}`;
          payload[cfg.idKey] = id;
        }
        if (cfg.reorderKey) payload[cfg.reorderKey] = rows.reduce((m, r) => Math.max(m, Number(r[cfg.reorderKey!]) || 0), 0) + 1;
        const { error: err } = await supabase.from(cfg.table).insert({ ...payload, ...(cfg.fixedOnCreate ?? {}) });
        if (err) throw new Error(err.message);
      } else {
        const { data, error: err } = await supabase.from(cfg.table).update(payload).eq(cfg.idKey, (editing as Row)[cfg.idKey]).select(cfg.idKey);
        if (err) throw new Error(err.message);
        if (!data || data.length === 0) throw new Error("Not saved. Make sure your account is an admin in the staff table.");
        if (oldPath) void deleteImagePaths([oldPath]);
      }
      if (cfg.flagKey && !cfg.gated) { await markManaged(cfg.flagKey); setManaged(true); }
      setEditing(null);
      await afterChange();
    } catch (e) {
      setFormError(e instanceof Error ? e.message : "Save failed");
    } finally { setSaving(false); }
  };

  const remove = async (ids: string[]) => {
    const targets = rows.filter((r) => ids.includes(String(r[cfg.idKey])));
    const paths = targets.map((r) => r.image_path).filter(Boolean) as string[];
    const { data, error: err } = await supabase.from(cfg.table).delete().in(cfg.idKey, ids).select(cfg.idKey);
    if (err) throw new Error(err.message);
    if (!data || data.length === 0) throw new Error("Nothing was deleted. Make sure your account is an admin in the staff table.");
    void deleteImagePaths(paths);
    sel.clear(); setConfirmIds(null);
    setMsg(`${data.length} deleted.`);
    await afterChange();
  };

  const setFlag = async (ids: string[], on: boolean) => {
    if (!cfg.toggle) return;
    await applyPatch(ids, { [cfg.toggle.key]: on });
  };

  const applyPatch = async (ids: string[], patch: Row) => {
    const { error: err } = await supabase.from(cfg.table).update(patch).in(cfg.idKey, ids);
    if (err) return setMsg(err.message);
    setMsg(`${ids.length} updated.`);
    sel.clear();
    await afterChange();
  };

  const toggleSwitch = async (r: Row, key: string) => {
    const { error: err } = await supabase.from(cfg.table).update({ [key]: !r[key] }).eq(cfg.idKey, r[cfg.idKey]);
    if (err) return setMsg(err.message);
    await afterChange();
  };

  const saveInline = async (r: Row, key: string, raw: string) => {
    const n = Number(raw);
    if (!Number.isFinite(n) || n === Number(r[key])) return;
    const { error: err } = await supabase.from(cfg.table).update({ [key]: n }).eq(cfg.idKey, r[cfg.idKey]);
    if (err) return setMsg(err.message);
    setMsg("Saved.");
    await afterChange();
  };

  const move = async (r: Row, dir: -1 | 1) => {
    if (!cfg.reorderKey) return;
    const k = cfg.reorderKey;
    const i = visible.findIndex((x) => x[cfg.idKey] === r[cfg.idKey]);
    const other = visible[i + dir];
    if (!other) return;
    const a = r[k], b = other[k];
    await Promise.all([
      supabase.from(cfg.table).update({ [k]: b }).eq(cfg.idKey, r[cfg.idKey]),
      supabase.from(cfg.table).update({ [k]: a }).eq(cfg.idKey, other[cfg.idKey]),
    ]);
    await afterChange();
  };

  /* ---- first-time gate ---- */
  if (managed === false) {
    return (
      <div className="border border-dashed border-border p-8 max-w-2xl">
        <p className="font-display text-xl font-bold mb-2">{cfg.title}</p>
        <p className="text-sm font-body text-muted-foreground mb-4">
          The website is currently showing its built-in {cfg.noun}s. To start managing them here, load the current ones into the dashboard first — nothing changes on the site until you edit something.
        </p>
        {error && <p className="text-sm text-destructive mb-3">{error}</p>}
        <div className="flex flex-wrap gap-2">
          {cfg.importDefaults && (
            <button className={primaryBtn} disabled={importing} onClick={() => void loadCurrent()}>
              {importing ? <Loader2 size={16} className="animate-spin" /> : <Upload size={16} />} Load current {cfg.noun}s
            </button>
          )}
          <button className={ghostBtn} disabled={importing} onClick={() => void startEmpty()}>Start empty</button>
        </div>
        {importing && <p className="text-xs text-muted-foreground mt-3">Copying images to GitHub — this can take a minute…</p>}
      </div>
    );
  }
  if (managed === null) return <p className="text-sm text-muted-foreground">Loading…</p>;

  return (
    <div>
      <div className="flex flex-wrap items-center gap-3 mb-4">
        <div className="relative flex-1 min-w-[180px] max-w-xs">
          <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-muted-foreground" />
          <input className={inputCls + " pl-9"} placeholder={`Search ${cfg.noun}s…`} value={search} onChange={(e) => setSearch(e.target.value)} />
        </div>
        {(cfg.filters ?? []).map((f) => (
          <select key={f.key} className={inputCls + " w-auto"} value={filterVals[f.key] ?? ""} onChange={(e) => setFilterVals({ ...filterVals, [f.key]: e.target.value })}>
            <option value="">{f.label}: all</option>
            {f.options.map((o) => <option key={o.value} value={o.value}>{o.label}</option>)}
          </select>
        ))}
        <button className={primaryBtn + " ml-auto"} onClick={openNew}><Plus size={16} /> New {cfg.noun}</button>
      </div>
      {cfg.intro && <p className="text-xs font-body text-muted-foreground mb-3">{cfg.intro}</p>}
      {(error || msg) && <p className={`text-sm font-body mb-3 ${error ? "text-destructive" : ""}`}>{error || msg}</p>}

      <div className="border border-border">
        <div className="px-4 pt-3 pb-2 text-sm font-body text-muted-foreground">{visible.length} {cfg.noun}{visible.length === 1 ? "" : "s"}</div>
        <Table fitViewport>
          <TableHeader>
            <TableRow>
              <TableHead className={stickyCheckHead}>
                <Checkbox
                  checked={selectedIds.length > 0 && selectedIds.length === visibleIds.length ? true : selectedIds.length > 0 ? "indeterminate" : false}
                  onCheckedChange={(v) => sel.setMany(visibleIds, v === true)}
                  aria-label="Select all"
                />
              </TableHead>
              <TableHead className={stickySnHead}>S/N</TableHead>
              {cfg.columns.map((c) => <TableHead key={c.label}>{c.label}</TableHead>)}
              <TableHead>Actions</TableHead>
            </TableRow>
          </TableHeader>
          <TableBody>
            {loading ? (
              <TableRow><TableCell colSpan={cfg.columns.length + 3} className="text-center py-8 text-muted-foreground">Loading…</TableCell></TableRow>
            ) : visible.length === 0 ? (
              <TableRow><TableCell colSpan={cfg.columns.length + 3} className="text-center py-8 text-muted-foreground">Nothing here yet.</TableCell></TableRow>
            ) : visible.map((r, i) => {
              const id = String(r[cfg.idKey]);
              return (
                <TableRow key={id} className={sel.ids.has(id) ? "bg-muted/60" : ""}>
                  <TableCell className={stickyCheckCell(sel.ids.has(id))}>
                    <Checkbox checked={sel.ids.has(id)} onCheckedChange={() => sel.toggle(id)} aria-label="Select row" />
                  </TableCell>
                  <TableCell className={stickySnCell(sel.ids.has(id))}>{i + 1}</TableCell>
                  {cfg.columns.map((c) => (
                    <TableCell key={c.label} className="align-middle">
                      {c.switch ? (
                        <div className="flex items-center gap-3">
                          <button
                            role="switch"
                            aria-checked={!!r[c.switch.key]}
                            aria-label={`${id} ${r[c.switch.key] ? "active" : "off"}`}
                            onClick={() => void toggleSwitch(r, c.switch!.key)}
                            className={`relative inline-flex h-6 w-11 shrink-0 items-center rounded-full transition-colors ${r[c.switch.key] ? "bg-green-600" : "bg-muted-foreground/40"}`}
                          >
                            <span className={`inline-block h-5 w-5 rounded-full bg-white shadow transition-transform ${r[c.switch.key] ? "translate-x-[22px]" : "translate-x-0.5"}`} />
                          </button>
                          <span className="text-xs font-body font-bold tracking-widest w-14">{r[c.switch.key] ? "ACTIVE" : "OFF"}</span>
                        </div>
                      ) : c.inline ? (
                        <input
                          key={`${id}-${r[c.inline.key]}`}
                          type="number"
                          defaultValue={r[c.inline.key]}
                          onBlur={(e) => void saveInline(r, c.inline!.key, e.target.value)}
                          className={inputCls + " w-32"}
                        />
                      ) : c.render?.(r)}
                    </TableCell>
                  ))}
                  <TableCell className="whitespace-nowrap">
                    {cfg.reorderKey && (
                      <>
                        <button className="p-1.5 text-muted-foreground hover:text-foreground disabled:opacity-30" disabled={i === 0} onClick={() => void move(r, -1)} aria-label="Move up"><ArrowUp size={14} /></button>
                        <button className="p-1.5 text-muted-foreground hover:text-foreground disabled:opacity-30" disabled={i === visible.length - 1} onClick={() => void move(r, 1)} aria-label="Move down"><ArrowDown size={14} /></button>
                      </>
                    )}
                    <button className="p-1.5 text-muted-foreground hover:text-foreground" onClick={() => openEdit(r)} aria-label="Edit"><Pencil size={14} /></button>
                    <button className="p-1.5 text-muted-foreground hover:text-destructive" onClick={() => setConfirmIds([id])} aria-label="Delete"><Trash2 size={14} /></button>
                  </TableCell>
                </TableRow>
              );
            })}
          </TableBody>
        </Table>
      </div>

      <BulkActionBar count={selectedIds.length} noun={cfg.noun} onClear={sel.clear}>
        {cfg.toggle && (
          <>
            <BulkButton onClick={() => void setFlag(selectedIds, true)}>{cfg.toggle.on}</BulkButton>
            <BulkButton onClick={() => void setFlag(selectedIds, false)}>{cfg.toggle.off}</BulkButton>
          </>
        )}
        {(cfg.bulkActions ?? []).map((a) => (
          <BulkButton key={a.label} onClick={() => void applyPatch(selectedIds, a.patch)}>{a.label}</BulkButton>
        ))}
        <BulkButton danger onClick={() => setConfirmIds(selectedIds)}>DELETE</BulkButton>
      </BulkActionBar>

      {confirmIds && (
        <ConfirmDialog
          title={`Delete ${confirmIds.length} ${cfg.noun}${confirmIds.length === 1 ? "" : "s"}?`}
          message="This removes it from the website. This cannot be undone."
          confirmLabel={`Delete ${confirmIds.length}`}
          destructive
          onClose={() => setConfirmIds(null)}
          onConfirm={() => remove(confirmIds)}
        />
      )}

      {editing && (
        <div className="fixed inset-0 z-50 bg-black/60 flex items-start justify-center overflow-y-auto overscroll-contain px-4" data-lenis-prevent onClick={() => setEditing(null)}>
          <div className="bg-background w-full max-w-2xl my-8 md:my-14 p-6 relative" onClick={(e) => e.stopPropagation()}>
            <button className="absolute top-4 right-4 p-1 hover:opacity-70" onClick={() => setEditing(null)} aria-label="Close"><X size={20} /></button>
            <h2 className="font-display text-2xl font-bold mb-5">{editing === "new" ? `New ${cfg.noun}` : `Edit ${cfg.noun}`}</h2>
            <div className="grid grid-cols-2 gap-4">
              {cfg.fields.map((f) => (
                <div key={f.key} className={f.half ? "col-span-2 sm:col-span-1" : "col-span-2"}>
                  {f.type === "bool" ? (
                    <label className="flex items-center gap-2 text-sm font-body">
                      <Checkbox checked={!!values[f.key]} onCheckedChange={(v) => setValues({ ...values, [f.key]: v === true })} /> {f.label}
                    </label>
                  ) : (
                    <>
                      <label className="block text-xs font-body font-bold tracking-widest mb-1">{f.label.toUpperCase()}{f.required ? " *" : ""}</label>
                      {f.type === "textarea" || f.type === "lines" ? (
                        <textarea className={inputCls} rows={f.rows ?? 4} value={values[f.key] ?? ""} onChange={(e) => setValues({ ...values, [f.key]: e.target.value })} />
                      ) : f.type === "select" ? (
                        <select className={inputCls} disabled={f.lockOnEdit && editing !== "new"} value={values[f.key] ?? ""} onChange={(e) => setValues({ ...values, [f.key]: e.target.value })}>
                          {f.options!.map((o) => <option key={o.value} value={o.value}>{o.label}</option>)}
                        </select>
                      ) : f.type === "image" ? (
                        <ImagePicker
                          url={values[f.key] ?? ""}
                          folder={cfg.imageFolder ?? cfg.table}
                          onPicked={({ url, path }) => {
                            const prev = f.pathKey ? (values[f.pathKey] as string | null) : null;
                            if (prev && !oldPath && editing !== "new") setOldPath(prev);
                            setValues({ ...values, [f.key]: url, ...(f.pathKey ? { [f.pathKey]: path } : {}) });
                          }}
                        />
                      ) : (
                        <input
                          className={inputCls}
                          type={f.type === "number" ? "number" : f.type === "date" ? "date" : "text"}
                          disabled={f.lockOnEdit && editing !== "new"}
                          value={values[f.key] ?? ""}
                          onChange={(e) => setValues({ ...values, [f.key]: e.target.value })}
                        />
                      )}
                      {f.help && <p className="text-[11px] text-muted-foreground font-body mt-1">{f.help}</p>}
                    </>
                  )}
                </div>
              ))}
            </div>
            {formError && <p className="text-sm text-destructive font-body mt-4">{formError}</p>}
            <div className="flex gap-2 mt-6">
              <button className={primaryBtn} disabled={saving} onClick={() => void save()}>
                {saving && <Loader2 size={16} className="animate-spin" />} Save
              </button>
              <button className={ghostBtn} onClick={() => setEditing(null)}>Cancel</button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};

export default EntityManager;
